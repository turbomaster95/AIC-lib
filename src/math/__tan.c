#include "libm.h"

double __tan(double x, double y, int iy) {
    static const double
        T1 = 3.33333333333334091986e-01,
        T2 = 1.33333333333201242699e-01,
        T3 = 5.39682539762260546775e-02,
        T4 = 2.18694882948595424599e-02,
        T5 = 8.86323982359930005737e-03,
        T6 = 3.59211286486176026068e-03,
        T7 = 1.45620945433529014891e-03,
        T8 = 5.88041240820264096874e-04,
        T9 = 2.46463134818469906812e-04,
        T10 = 7.81794442939557092300e-05,
        T11 = 7.14072491382608190305e-05,
        T12 = -1.85586374822087169418e-05,
        T13 = 2.59073051863633712884e-05,
        T14 = -1.01153079520070220149e-05;

    double z, r, v, w, s;
    z = x * x;
    w = z * z;
    r = T9 + w * (T11 + w * T13);
    v = (T7 + w * (T10 + w * (T12 + w * T14))) / (1.0 + w * (T8 + w * r));
    s = z * x;
    r = y + s * (T1 + w * (T2 + w * (T3 + w * (T4 + w * (T5 + w * (T6 + w * v))))));
    if (iy == 1)
        return -r - x;
    else
        return r - x;
}
